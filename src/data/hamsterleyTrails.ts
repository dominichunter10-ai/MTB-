export function haversineKm(a: { lat: number; lng: number }, b: { lat: number; lng: number }): number {
  const R = 6371;
  const dLat = ((b.lat - a.lat) * Math.PI) / 180;
  const dLng = ((b.lng - a.lng) * Math.PI) / 180;
  const lat1 = (a.lat * Math.PI) / 180;
  const lat2 = (b.lat * Math.PI) / 180;
  const s =
    Math.sin(dLat / 2) * Math.sin(dLat / 2) +
    Math.cos(lat1) * Math.cos(lat2) * Math.sin(dLng / 2) * Math.sin(dLng / 2);
  return 2 * R * Math.atan2(Math.sqrt(s), Math.sqrt(1 - s));
}

export function bearingDegrees(a: { lat: number; lng: number }, b: { lat: number; lng: number }): number {
  const lat1 = (a.lat * Math.PI) / 180;
  const lat2 = (b.lat * Math.PI) / 180;
  const dLng = ((b.lng - a.lng) * Math.PI) / 180;
  const y = Math.sin(dLng) * Math.cos(lat2);
  const x = Math.cos(lat1) * Math.sin(lat2) - Math.sin(lat1) * Math.cos(lat2) * Math.cos(dLng);
  return ((Math.atan2(y, x) * 180) / Math.PI + 360) % 360;
}

export function compassDirection(deg: number): string {
  const dirs = ['N', 'NE', 'E', 'SE', 'S', 'SW', 'W', 'NW'];
  return dirs[Math.round(deg / 45) % 8];
}

export function distanceToTrailMeters(
  pos: { lat: number; lng: number },
  trail: Trail
): { minMeters: number; nearestIndex: number } {
  let minKm = Infinity;
  let nearestIndex = 0;
  for (let i = 0; i < trail.coordinates.length; i++) {
    const d = haversineKm(pos, trail.coordinates[i]);
    if (d < minKm) {
      minKm = d;
      nearestIndex = i;
    }
  }
  return { minMeters: Math.round(minKm * 1000), nearestIndex };
}

export function computeLiveTrailRating(
  trail: Trail,
  hazards: HazardReport[],
  votes: DifficultyVote[]
): LiveTrailRating {
  const activeTrailHazards = hazards.filter(
    (h) => h.trailId === trail.id && h.status === 'active'
  );
  const trailVotes = votes.filter((v) => v.trailId === trail.id);

  let hazardDelta = 0;
  let maxSeverity = 0;
  for (const h of activeTrailHazards) {
    const meta = HAZARD_TYPE_META[h.hazardType];
    const weight = h.hazardType === 'clear_trail' ? 1 : 0.7 + h.severity * 0.15;
    hazardDelta += meta.impactDelta * weight;
    if (h.hazardType !== 'clear_trail' && h.severity > maxSeverity) {
      maxSeverity = h.severity;
    }
  }
  hazardDelta = Math.max(-0.4, Math.min(1.1, hazardDelta));

  let voteDelta = 0;
  let dominantSurface: SurfaceCondition = 'hero_dirt';
  if (trailVotes.length > 0) {
    const avgVote = trailVotes.reduce((acc, v) => acc + v.rating, 0) / trailVotes.length;
    voteDelta = (avgVote - trail.baseDifficulty) * 0.35;

    const surfaceCounts: Record<string, number> = {};
    for (const v of trailVotes) {
      surfaceCounts[v.surfaceCondition] = (surfaceCounts[v.surfaceCondition] || 0) + 1;
    }
    let bestSurface: SurfaceCondition = 'hero_dirt';
    let bestCount = -1;
    for (const [surf, count] of Object.entries(surfaceCounts)) {
      if (count > bestCount) {
        bestCount = count;
        bestSurface = surf as SurfaceCondition;
      }
    }
    dominantSurface = bestSurface;
    voteDelta += SURFACE_META[dominantSurface].delta * 0.4;
  }

  const rawLive = trail.baseDifficulty + hazardDelta + voteDelta;
  const liveDifficulty = Math.round(Math.max(1.0, Math.min(5.0, rawLive)) * 10) / 10;
  const delta = Math.round((liveDifficulty - trail.baseDifficulty) * 10) / 10;

  let statusLabel: LiveTrailRating['statusLabel'] = 'Running Fast';
  if (maxSeverity >= 3) {
    statusLabel = 'Hazard Alert';
  } else if (delta >= 0.4 || maxSeverity === 2) {
    statusLabel = 'Caution Advised';
  } else if (dominantSurface === 'greasy_roots' || dominantSurface === 'muddy_bog') {
    statusLabel = 'Technical / Wet';
  } else if (dominantSurface === 'hero_dirt') {
    statusLabel = 'Tacky / Hero';
  }

  return {
    baseDifficulty: trail.baseDifficulty,
    liveDifficulty,
    delta,
    activeHazardsCount: activeTrailHazards.filter((h) => h.hazardType !== 'clear_trail').length,
    maxHazardSeverity: maxSeverity,
    dominantSurface,
    voteCount: trailVotes.length,
    statusLabel,
  };
}
